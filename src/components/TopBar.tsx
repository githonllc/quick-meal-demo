// fallback is where Back goes when there is no page to go back to (a direct link).
export function TopBar({ title, right, fallback = '/' }: { title?: string; right?: ReactNode; fallback?: string }) {
  return (
    <div className="topbar">
      <button className="icon-btn" aria-label="Back" onClick={() => back(fallback)}>
        <BackIcon />
      </button>
      {title && <h1>{title}</h1>}
      <div className="icon-btn">{right}</div>
    </div>
  )
}
